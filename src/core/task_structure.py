"""
TaskStructureAnalyzer - Task Structure Analyzer (Dynamic Analysis Version)

Analyzes task internal structure, dynamically identifies section roles and content dependencies.

Core design concepts:
1. No hardcoded section types, instead dynamically analyze each section's "role"
2. Use LLM to analyze dependencies between sections
3. Dynamically generate execution plan based on analysis results

Section roles (SectionRole):
- DATA_COLLECTION: Data collection type (collect raw data)
- ANALYSIS: Analysis type (analyze data)
- SYNTHESIS: Synthesis type (needs other sections to complete before generating)
- SUPPORTING: Supporting type (appendix, data sources, etc.)

Design document: .sisyphus/plans/intelligent_routing_system_design.md
"""

