class SectionRole(Enum):
    """
    Section role (dynamic analysis result)

    Not predefined types, but roles dynamically determined based on section content.

    Role definitions:
    - DATA_COLLECTION: Data collection type - collects raw data, no dependency on other sections
    - ANALYSIS: Analysis type - analyzes data, may depend on data collection sections
    - SYNTHESIS: Synthesis type - needs other sections to complete before generating (e.g. summary, conclusion)
    - SUPPORTING: Supporting type - appendix, data sources and other supporting content
    """
    DATA_COLLECTION = "data_collection"
    ANALYSIS = "analysis"
    SYNTHESIS = "synthesis"
    SUPPORTING = "supporting"


@dataclass
class SectionSpec:
    """
    Section Specification

    Describes a section's role, dependencies and execution characteristics.
    Dynamically generated by LLM analysis, not using predefined templates.
    """
    section_id: str                         # Unique identifier
    section_name: str                       # Section name
    section_role: SectionRole               # Section role (dynamic analysis result)
    role_reasoning: str = ""                # Role reasoning (LLM output)
    content_dependency: List[str] = field(default_factory=list)  # Dependent section IDs
    dependency_reasoning: str = ""          # Dependency reasoning
    skill_requirements: List[str] = field(default_factory=list)  # Required Skills
    estimated_complexity: str = "medium"    # "low" / "medium" / "high"
    can_parallel: bool = True               # Whether can parallelize with other sections
    priority: int = 0                       # Execution priority

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary"""
        return {
            "section_id": self.section_id,
            "section_name": self.section_name,
            "section_role": self.section_role.value,
            "role_reasoning": self.role_reasoning,
            "content_dependency": self.content_dependency,
            "dependency_reasoning": self.dependency_reasoning,
            "skill_requirements": self.skill_requirements,
            "estimated_complexity": self.estimated_complexity,
            "can_parallel": self.can_parallel,
            "priority": self.priority,
        }


@dataclass
class ContentDependency:
    """
    Content Dependency

    Describes content dependencies between sections, dynamically generated by LLM analysis.
    """
    from_section: str                       # Source section ID
    to_section: str                         # Target section ID
    dependency_type: str                    # "data" / "analysis" / "synthesis"
    dependency_reason: str = ""             # Dependency reason (LLM output)
    unlock_condition: str = "completion"    # "completion" / "quality_threshold" / "both"
    quality_threshold: float = 0.75

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary"""
        return {
            "from_section": self.from_section,
            "to_section": self.to_section,
            "dependency_type": self.dependency_type,
            "dependency_reason": self.dependency_reason,
            "unlock_condition": self.unlock_condition,
            "quality_threshold": self.quality_threshold,
        }


@dataclass
class TaskStructure:
    """
    Task Structure

    Complete description of a task's internal structure and execution characteristics.
    """
    task_id: str
    topic: str
    sections: List[SectionSpec] = field(default_factory=list)
    dependencies: List[ContentDependency] = field(default_factory=list)
    execution_graph: Dict[str, List[str]] = field(default_factory=dict)
    parallel_groups: List[List[str]] = field(default_factory=list)
    critical_path: List[str] = field(default_factory=list)
    total_estimated_agents: int = 0
    analysis_method: str = "rule_based"     # "rule_based" / "llm_based"

    def get_section_by_id(self, section_id: str) -> Optional[SectionSpec]:
        """Get section by ID"""
        for section in self.sections:
            if section.section_id == section_id:
                return section
        return None

    def get_sections_by_role(self, role: SectionRole) -> List[SectionSpec]:
        """Get sections by role"""
        return [s for s in self.sections if s.section_role == role]

    def get_data_collection_sections(self) -> List[SectionSpec]:
        """Get all data collection sections"""
        return self.get_sections_by_role(SectionRole.DATA_COLLECTION)

    def get_analysis_sections(self) -> List[SectionSpec]:
        """Get all analysis sections"""
        return self.get_sections_by_role(SectionRole.ANALYSIS)

    def get_synthesis_sections(self) -> List[SectionSpec]:
        """Get all synthesis sections"""
        return self.get_sections_by_role(SectionRole.SYNTHESIS)
    
    def get_data_dependencies(self, section_name: str) -> List[str]:
        """R-FIX-2: infer upstream section IDs this section depends on for data.
        Uses keyword mapping; returns matching section IDs.
        """
        _DATA_DEP_MAP = {
            "财务": ["营收", "利润", "盈利", "收入", "成本"],
            "盈利": ["营收", "利润", "收入", "成本", "毛利率"],
            "销量": ["财务", "营收", "利润", "出口", "海外"],
            "市场": ["财务", "销量", "竞争", "份额"],
            "竞争": ["财务", "市场", "盈利"],
            "研发": ["财务", "盈利", "收入"],
            "风险": ["财务", "竞争", "政策", "海外"],
            "国际化": ["财务", "销量", "盈利"],
            "预测": ["财务", "盈利", "研发", "国际化", "竞争"],
            "季度": ["财务", "盈利", "销量"],
        }
        name_lower = section_name.lower()
        upstream, seen = [], set()
        for kw, deps in _DATA_DEP_MAP.items():
            if kw in name_lower:
                for dep in deps:
                    for s in self.sections:
                        if dep in s.section_name.lower() and s.section_id not in seen:
                            seen.add(s.section_id)
                            upstream.append(s.section_id)
        return upstream
    
    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary"""
        return {
            "task_id": self.task_id,
            "topic": self.topic,
            "sections": [s.to_dict() for s in self.sections],
            "dependencies": [d.to_dict() for d in self.dependencies],
            "execution_graph": self.execution_graph,
            "parallel_groups": self.parallel_groups,
            "critical_path": self.critical_path,
            "total_estimated_agents": self.total_estimated_agents,
            "analysis_method": self.analysis_method,
        }


