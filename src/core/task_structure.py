class TaskStructureAnalyzer:
    """
    Task Structure Analyzer (Dynamic Analysis Version)

    Core concepts:
    1. No hardcoded section types
    2. Dynamically analyze each section's role
    3. Dynamically identify dependencies between sections
    4. Generate execution plan based on analysis results

    Usage example:
        analyzer = TaskStructureAnalyzer(use_llm=True)
        structure = analyzer.analyze(
            intent=deep_intent,
            aspects=["Market Size", "Competitive Landscape", "Technology Trends", "Executive Summary"]
        )
    """

    # Synthesis section keywords (for rule engine quick judgment)
    SYNTHESIS_KEYWORDS = [
        # Summary type
        "摘要", "执行摘要", "核心摘要", "summary", "executive summary",
        "核心洞察", "关键发现", "key insights", "key findings",
        # Conclusion type
        "结论", "研究结论", "总结", "研究总结", "conclusion", "findings",
        # Synthesis type
        "综合分析", "综合研判", "整体分析", "综合评估",
        # Forecast / outlook type (added P2)
        "趋势预测", "价格展望", "后市判断", "后市分析",
        "前景预测", "走势分析", "趋势研判",
        "forecast", "outlook", "projection",
    ]

    # Supporting section keywords
    SUPPORTING_KEYWORDS = [
        "附录", "appendix", "数据来源", "data source",
        "参考文献", "references", "研究方法", "methodology",
    ]

    # Data collection section keywords
    DATA_COLLECTION_KEYWORDS = [
        "数据收集", "数据采集", "信息收集", "data collection",
        "调研", "survey", "问卷", "访谈", "interview",
    ]

    def __init__(
        self,
        use_llm: bool = True,
        fallback_to_rule: bool = True,
        llm_model: Optional[str] = None,
    ):
        """
        Initialize task structure analyzer

        Args:
            use_llm: Whether to use LLM for dynamic analysis
            fallback_to_rule: Whether to fallback to rule engine when LLM fails
            llm_model: Specify LLM model
        """
        self._use_llm = use_llm
        self._fallback_to_rule = fallback_to_rule
        self._llm_model = llm_model
        self._llm_skill = None

        logger.info(f"TaskStructureAnalyzer initialized: use_llm={use_llm}, fallback={fallback_to_rule}")

    def _get_llm_skill(self):
        """Lazily get LLM Skill"""
        if self._llm_skill is None:
            try:
                from src.skills.llm_skill import LLMSkill
            except ImportError:
                import sys
                from pathlib import Path
                project_root = Path(__file__).parent.parent.parent
                if str(project_root) not in sys.path:
                    sys.path.insert(0, str(project_root))
                from src.skills.llm_skill import LLMSkill
            self._llm_skill = LLMSkill()
        return self._llm_skill
    
    def analyze(
        self,
        intent: DeepIntentResult,
        aspects: List[str],
        task_id: Optional[str] = None,
        topic: Optional[str] = None,
    ) -> TaskStructure:
        """
        Analyze task structure

        Args:
            intent: Deep intent analysis result
            aspects: Section list
            task_id: Task ID
            topic: Report topic

        Returns:
            TaskStructure: Task structure
        """
        import uuid
        task_id = task_id or f"task_{uuid.uuid4().hex[:8]}"

        # Ensure topic has value (type safety)
        if topic is None:
            topic = intent.domain_context.get("industry", "") or "Research Topic"

        # At this point topic type is confirmed as str
        assert topic is not None

        logger.info(f"[{task_id}] Analyzing task structure: {len(aspects)} sections")

        # Try LLM analysis
        if self._use_llm:
            try:
                # P1-2: Detect whether we're inside a running event loop.
                # asyncio.run() raises RuntimeError when called from within
                # an async context (e.g. an orchestrator running on an asyncio server).
                try:
                    loop = asyncio.get_running_loop()
                except RuntimeError:
                    loop = None

                if loop is not None:
                    # We are inside an async context — schedule the coroutine
                    # on the existing loop rather than creating a new one.
                    future = asyncio.ensure_future(
                        self._analyze_with_llm(intent, aspects, task_id, topic),
                        loop=loop,
                    )
                    # Run until complete in a thread-safe manner.
                    # Note: this blocks the caller but does NOT attempt to
                    # create a new event loop.
                    if not loop.is_running():
                        return loop.run_until_complete(future)
                    else:
                        # Loop is running (we're inside an async handler).
                        # Use run_coroutine_threadsafe on a dedicated thread
                        # as a fallback to avoid deadlock.
                        import concurrent.futures
                        with concurrent.futures.ThreadPoolExecutor() as pool:
                            return pool.submit(
                                asyncio.run,
                                self._analyze_with_llm(intent, aspects, task_id, topic),
                            ).result(timeout=120)
                else:
                    return asyncio.run(self._analyze_with_llm(
                        intent, aspects, task_id, topic
                    ))
            except Exception as e:
                logger.warning(f"LLM structure analysis failed: {e}")
                if self._fallback_to_rule:
                    logger.info("Falling back to rule-based analysis")
                    return self._analyze_with_rules(intent, aspects, task_id, topic)
                raise

        # Use rule engine
        return self._analyze_with_rules(intent, aspects, task_id, topic)

    async def _analyze_with_llm(
        self,
        intent: DeepIntentResult,
        aspects: List[str],
        task_id: str,
        topic: str,
    ) -> TaskStructure:
        """Use LLM for dynamic structure analysis"""
        llm_skill = self._get_llm_skill()

        # Load section analysis prompt from PromptManager
        pm = PromptManager.get_instance()
        try:
            system_prompt = pm.render("agents", "section_analysis_system")
            user_template = pm.render("agents", "section_analysis_user")
        except FileNotFoundError:
            logger.warning("Section analysis prompt files not found, using fallback")
            system_prompt = "You are a professional report structure analysis expert. Please analyze the role and dependencies of report sections."
            user_template = "Please analyze the following report's section structure:\n\nReport topic: {topic}\nSection list: {sections}\n\nPlease output each section's role analysis and dependencies (JSON format)."

        # Escape curly braces in topic to prevent str.format injection
        safe_topic = topic.replace("{", "{{").replace("}", "}}")
        prompt = user_template.format(
            topic=safe_topic,
            sections=json.dumps(aspects, ensure_ascii=False),
        )

        # Call LLM
        result = await llm_skill.execute(
            prompt=prompt,
            system_prompt=system_prompt,
            model=self._llm_model,
            max_tokens=2048,
            temperature=0.1,
        )
        
        if not result.get("success"):
            raise ValueError(f"LLM call failed: {result.get('error')}")

        content = result.get("content", "")

        # Parse JSON
        llm_output = self._parse_llm_json(content)

        # Build TaskStructure
        return self._build_structure_from_llm(
            llm_output, aspects, task_id, topic, intent
        )

    def _parse_llm_json(self, content: str) -> Dict[str, Any]:
        """Parse LLM output JSON"""
        content = content.strip()
        
        if content.startswith("```json"):
            content = content[7:]
        if content.startswith("```"):
            content = content[3:]
        if content.endswith("```"):
            content = content[:-3]
        
        content = content.strip()
        
        try:
            result = json.loads(content)
        except json.JSONDecodeError as e:
            logger.warning(f"Failed to parse LLM JSON: {e}")
            logger.debug(f"Raw LLM output: {content[:500]}")
            return {"sections": [], "reasoning": "LLM returned invalid JSON"}
        
        # Guard: LLM may return a JSON array instead of an object
        if isinstance(result, list):
            logger.warning(
                f"LLM returned a JSON array ({len(result)} items) instead of an object. "
                f"Wrapping in {{\"sections\": ...}}"
            )
            return {"sections": result}
        if not isinstance(result, dict):
            logger.warning(
                f"LLM returned unexpected type {type(result).__name__}, "
                f"returning empty dict as fallback"
            )
            return {}
        return result
    
    def _build_structure_from_llm(
        self,
        llm_output: Dict[str, Any],
        aspects: List[str],
        task_id: str,
        topic: str,
        intent: DeepIntentResult,
    ) -> TaskStructure:
        """Build TaskStructure from LLM output"""
        sections = []
        section_id_map = {}  # name -> id

        # Parse section analysis results
        section_analyses = llm_output.get("sections", [])

        for i, aspect in enumerate(aspects):
            section_id = f"section_{i}_{self._sanitize_id(aspect)}"
            section_id_map[aspect] = section_id

            # Find LLM analysis for this section
            analysis = None
            for sa in section_analyses:
                if sa.get("name") == aspect or sa.get("section_name") == aspect:
                    analysis = sa
                    break

            if analysis:
                # Use LLM analysis result
                role_str = analysis.get("role", "analysis").upper()
                try:
                    role = SectionRole[role_str]
                except KeyError:
                    role = SectionRole.ANALYSIS

                section = SectionSpec(
                    section_id=section_id,
                    section_name=aspect,
                    section_role=role,
                    role_reasoning=analysis.get("role_reasoning", ""),
                    skill_requirements=analysis.get("skills", ["llm_skill"]),
                    can_parallel=analysis.get("can_parallel", True),
                    estimated_complexity=analysis.get("complexity", "medium"),
                )
            else:
                # Fallback to rule judgment
                role = self._classify_section_role(aspect)
                section = SectionSpec(
                    section_id=section_id,
                    section_name=aspect,
                    section_role=role,
                    role_reasoning="Rule-based fallback",
                    can_parallel=role != SectionRole.SYNTHESIS,
                )

            sections.append(section)

        # Parse dependencies
        dependencies = []
        dep_analyses = llm_output.get("dependencies", [])

        for dep in dep_analyses:
            from_name = dep.get("from")
            to_name = dep.get("to")

            from_id = section_id_map.get(from_name)
            to_id = section_id_map.get(to_name)

            if from_id and to_id:
                dependencies.append(ContentDependency(
                    from_section=from_id,
                    to_section=to_id,
                    dependency_type=dep.get("type", "synthesis"),
                    dependency_reason=dep.get("reason", ""),
                ))

                # Update section's dependency list
                for s in sections:
                    if s.section_id == to_id:
                        s.content_dependency.append(from_id)

        # If LLM didn't output dependencies, use rule inference
        if not dependencies:
            dependencies = self._infer_dependencies(sections, intent)

        # Build execution graph
        execution_graph = self._build_execution_graph(sections, dependencies)
        parallel_groups = self._compute_parallel_groups(sections, dependencies)
        critical_path = self._compute_critical_path(sections, dependencies)
        total_agents = self._estimate_total_agents(sections, intent)

        return TaskStructure(
            task_id=task_id,
            topic=topic,
            sections=sections,
            dependencies=dependencies,
            execution_graph=execution_graph,
            parallel_groups=parallel_groups,
            critical_path=critical_path,
            total_estimated_agents=total_agents,
            analysis_method="llm_based",
        )

    def _analyze_with_rules(
        self,
        intent: DeepIntentResult,
        aspects: List[str],
        task_id: str,
        topic: str,
    ) -> TaskStructure:
        """Use rule engine for structure analysis (fallback)"""
        sections = []

        for i, aspect in enumerate(aspects):
            section_id = f"section_{i}_{self._sanitize_id(aspect)}"
            role = self._classify_section_role(aspect)

            section = SectionSpec(
                section_id=section_id,
                section_name=aspect,
                section_role=role,
                role_reasoning=f"Matched keywords for {role.value}",
                skill_requirements=self._infer_skills(aspect, role, intent),
                can_parallel=role != SectionRole.SYNTHESIS,
                estimated_complexity=self._estimate_complexity(aspect, intent),
            )
            sections.append(section)

        # Infer dependencies
        dependencies = self._infer_dependencies(sections, intent)

        # Build execution graph
        execution_graph = self._build_execution_graph(sections, dependencies)
        parallel_groups = self._compute_parallel_groups(sections, dependencies)
        critical_path = self._compute_critical_path(sections, dependencies)
        total_agents = self._estimate_total_agents(sections, intent)

        return TaskStructure(
            task_id=task_id,
            topic=topic,
            sections=sections,
            dependencies=dependencies,
            execution_graph=execution_graph,
            parallel_groups=parallel_groups,
            critical_path=critical_path,
            total_estimated_agents=total_agents,
            analysis_method="rule_based",
        )

    def _classify_section_role(self, aspect: str) -> SectionRole:
        """Use rules to determine section role"""
        aspect_lower = aspect.lower()

        # Check synthesis type
        # Short keywords (≤2 chars) use exact match to prevent false positives
        # e.g. "结论" should not match "数据结构"
        for kw in self.SYNTHESIS_KEYWORDS:
            kw_lower = kw.lower()
            if len(kw) <= 2:
                if kw_lower == aspect_lower:
                    return SectionRole.SYNTHESIS
            else:
                if kw_lower in aspect_lower:
                    return SectionRole.SYNTHESIS

        # Check supporting type
        for kw in self.SUPPORTING_KEYWORDS:
            kw_lower = kw.lower()
            if len(kw) <= 2:
                if kw_lower == aspect_lower:
                    return SectionRole.SUPPORTING
            else:
                if kw_lower in aspect_lower:
                    return SectionRole.SUPPORTING

        # Check data collection type
        for kw in self.DATA_COLLECTION_KEYWORDS:
            kw_lower = kw.lower()
            if len(kw) <= 2:
                if kw_lower == aspect_lower:
                    return SectionRole.DATA_COLLECTION
            else:
                if kw_lower in aspect_lower:
                    return SectionRole.DATA_COLLECTION

        # Default to analysis type
        return SectionRole.ANALYSIS

    def _infer_dependencies(
        self,
        sections: List[SectionSpec],
        intent: DeepIntentResult,
    ) -> List[ContentDependency]:
        """
        Infer dependencies between sections

        Rules:
        1. SYNTHESIS role sections depend on all ANALYSIS sections
        2. ANALYSIS sections may depend on DATA_COLLECTION sections
        """
        dependencies = []

        analysis_sections = [s for s in sections if s.section_role == SectionRole.ANALYSIS]
        synthesis_sections = [s for s in sections if s.section_role == SectionRole.SYNTHESIS]
        data_sections = [s for s in sections if s.section_role == SectionRole.DATA_COLLECTION]

        # Synthesis depends on all analysis
        for synthesis in synthesis_sections:
            for analysis in analysis_sections:
                dependencies.append(ContentDependency(
                    from_section=analysis.section_id,
                    to_section=synthesis.section_id,
                    dependency_type="synthesis",
                    dependency_reason="Synthesis section needs analysis sections to complete",
                ))
                synthesis.content_dependency.append(analysis.section_id)

            # Also depends on data collection
            for data in data_sections:
                dependencies.append(ContentDependency(
                    from_section=data.section_id,
                    to_section=synthesis.section_id,
                    dependency_type="synthesis",
                    dependency_reason="Synthesis section needs data collection sections to complete",
                ))
                synthesis.content_dependency.append(data.section_id)

        # Analysis depends on data collection (if exists)
        for analysis in analysis_sections:
            for data in data_sections:
                dependencies.append(ContentDependency(
                    from_section=data.section_id,
                    to_section=analysis.section_id,
                    dependency_type="data",
                    dependency_reason="Analysis section needs output from data collection sections",
                ))
                analysis.content_dependency.append(data.section_id)

        return dependencies

